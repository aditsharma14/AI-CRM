// The AI brief card: hidden while AI is off; generate, loading copy, result with citations that scroll to the history
// entry, copy, regenerate (refresh: true); each AI error says what happened, with Retry only where it can help. A 202
// is a queued job: polled at 1, 2, 4, then every 5 s, showing queued or running, until it ends; leaving stops it.
import { act, fireEvent, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { http } from 'msw'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'

import { makeUser } from '../../../tests/factories.js'
import { renderWithProviders } from '../../../tests/render.jsx'
import { API, fail, ok, server } from '../../../tests/server.js'
import { LeadBriefCard } from './LeadBriefCard.jsx'

const LEAD_ID = 'a'.repeat(24)
const NOTE_ID = '3'.repeat(24)
const JOB_ID = 'b'.repeat(24)
const HISTORY = [
  { id: NOTE_ID, kind: 'note', title: 'Note', text: 'Budget approved', date: '2026-11-03T16:00:00.000Z' },
]
const BRIEF = {
  summary: 'Ravi at Sahyadri is qualified; budget is approved.',
  nextAction: { action: 'Send the quote', dueDate: '2026-11-07' },
  followUpEmail: { subject: 'Your quote', body: 'Hi Ravi,\n\nThe quote follows.' },
  citations: [{ claim: 'budget is approved', sourceIds: [NOTE_ID] }],
  cached: false,
  provider: 'ollama',
  model: 'llama3.2:3b',
  promptVersion: 'lead-brief/1',
  truncated: 0,
  generatedAt: '2026-11-05T10:00:00.000Z',
}

function serve({ aiEnabled = true, answer } = {}) {
  const bodies = []
  server.use(
    http.get(`${API}/config`, () => ok({ emailEnabled: false, aiEnabled })),
    http.post(`${API}/ai/leads/:id/brief`, async ({ request }) => {
      bodies.push(await request.json())
      return answer ? answer(bodies.length) : ok(BRIEF)
    }),
  )
  return bodies
}

/** POST answers 202 with a job; each GET of it answers the next of `states` (the last one repeats). */
function serveJob(states) {
  const polls = []
  server.use(
    http.get(`${API}/config`, () => ok({ emailEnabled: false, aiEnabled: true })),
    http.post(`${API}/ai/leads/:id/brief`, () => ok({ jobId: JOB_ID }, null, 202)),
    http.get(`${API}/ai/jobs/:jobId`, ({ params }) => {
      polls.push({ at: Date.now(), jobId: params.jobId })
      return ok(states[Math.min(polls.length, states.length) - 1])
    }),
  )
  return polls
}

function renderCard() {
  const user = userEvent.setup()
  const view = renderWithProviders(
    <>
      <LeadBriefCard leadId={LEAD_ID} history={HISTORY} />
      <ol>
        <li id={`history-${NOTE_ID}`} tabIndex={-1}>
          Budget approved
        </li>
      </ol>
    </>,
    { session: makeUser('member') },
  )
  return Object.assign(user, { unmount: view.unmount })
}

beforeEach(() => {
  Element.prototype.scrollIntoView = vi.fn()
})
afterEach(() => vi.useRealTimers())

describe('LeadBriefCard', () => {
  it('is hidden while AI is off', async () => {
    serve({ aiEnabled: false })
    renderCard()
    await screen.findByText('Budget approved')
    await waitFor(() => expect(screen.queryByRole('heading', { name: 'AI brief' })).toBeNull())
    expect(screen.queryByRole('button', { name: /generate brief/i })).toBeNull()
  })

  it('generates: loading copy, then summary, next step, draft email and the AI note', async () => {
    let release
    const gate = new Promise((resolve) => (release = resolve))
    const bodies = serve({ answer: async () => (await gate, ok(BRIEF)) })
    const user = renderCard()
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    expect(await screen.findByRole('status')).toHaveTextContent('Generating… This can take a few seconds.')
    release()
    expect(await screen.findByText(BRIEF.summary)).toBeInTheDocument()
    expect(screen.getByText(/Send the quote/)).toBeInTheDocument()
    expect(screen.getByText('Your quote')).toBeInTheDocument()
    expect(screen.getByText(/Generated by AI, check before sending/)).toBeInTheDocument()
    expect(screen.getByText(/llama3\.2:3b/)).toBeInTheDocument()
    expect(bodies).toEqual([{}])
  })

  it('a citation scrolls to its history entry and highlights it for 2 seconds', async () => {
    serve()
    const user = renderCard()
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    const chip = await screen.findByRole('button', { name: /^Note · / })
    const entry = document.getElementById(`history-${NOTE_ID}`)
    vi.useFakeTimers({ shouldAdvanceTime: true })
    await user.click(chip)
    expect(entry.scrollIntoView).toHaveBeenCalledWith({ behavior: 'smooth', block: 'center' })
    expect(entry).toHaveFocus()
    expect(entry).toHaveClass('ring-2')
    act(() => vi.advanceTimersByTime(2000))
    expect(entry).not.toHaveClass('ring-2')
  })

  it('copies the email (subject and body), and never sends it', async () => {
    const bodies = serve()
    const user = renderCard() // user-event provides the clipboard
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    await user.click(await screen.findByRole('button', { name: /copy email/i }))
    expect(await navigator.clipboard.readText()).toBe('Subject: Your quote\n\nHi Ravi,\n\nThe quote follows.')
    expect(await screen.findByRole('button', { name: /copied/i })).toBeInTheDocument()
    expect(bodies).toHaveLength(1) // copying made no request
  })

  it('Regenerate asks for a fresh brief; a cached one says so; left-out items are mentioned', async () => {
    const bodies = serve({ answer: (n) => ok({ ...BRIEF, cached: n === 1, truncated: n === 2 ? 3 : 0 }) })
    const user = renderCard()
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    expect(await screen.findByText(/From cache/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /regenerate/i }))
    expect(await screen.findByText(/3 older items were left out/)).toBeInTheDocument()
    expect(bodies).toEqual([{}, { refresh: true }])
  })

  it.each([
    ['AI_UNAVAILABLE', 503, 'The AI took too long to answer. Try again in a moment.', true],
    ['AI_BAD_OUTPUT', 502, 'The AI could not write a usable brief for this lead. Try again.', true],
    ['AI_RATE_LIMITED', 429, 'Your workspace has used its 20 AI briefs for this hour. Try again in 12 minutes.', false],
  ])('%s shows its message%s', async (code, status, message, retry) => {
    const bodies = serve({ answer: (n) => (n === 1 ? fail(status, code, message) : ok(BRIEF)) })
    const user = renderCard()
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    expect(await screen.findByRole('alert')).toHaveTextContent(message)
    const retryButton = screen.queryByRole('button', { name: 'Retry' })
    expect(Boolean(retryButton)).toBe(retry)
    if (retry) {
      await user.click(retryButton)
      expect(await screen.findByText(BRIEF.summary)).toBeInTheDocument()
      expect(bodies).toHaveLength(2)
    }
  })

  it('a lost connection says so and offers Retry', async () => {
    serve({ answer: () => Response.error() })
    const user = renderCard()
    await user.click(await screen.findByRole('button', { name: /generate brief/i }))
    expect(await screen.findByRole('alert')).toHaveTextContent(/Can't reach the server/)
    expect(screen.getByRole('button', { name: 'Retry' })).toBeInTheDocument()
  })

  describe('a queued job (202)', () => {
    // Fake clock (setTimeout and Date only), installed once the card is on screen: the poll delays are asserted
    // exactly, and nothing waits for real seconds. Testing Library's findBy/waitFor poll on setTimeout, so after
    // that point the tests advance the clock and let real I/O (MSW, axios) settle instead, and click with fireEvent
    // (user-event waits on a setTimeout(0) that only Jest's fake timers advance on their own).
    const fakeClock = () => vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] })
    const settle = async () => {
      for (let i = 0; i < 10; i++) {
        await act(() => vi.advanceTimersByTimeAsync(0))
        // A real macrotask (the fake clock owns setTimeout): lets MSW and axios move on. Vitest runs on Node.
        await new Promise((resolve) => globalThis.setImmediate(resolve))
      }
    }
    const tick = async (ms) => {
      await act(() => vi.advanceTimersByTimeAsync(ms))
      await settle()
    }
    async function start(states) {
      const polls = serveJob(states)
      const { unmount } = renderCard()
      const button = await screen.findByRole('button', { name: /generate brief/i })
      fakeClock()
      const at = Date.now()
      fireEvent.click(button)
      await settle()
      return { polls, unmount, at }
    }

    it('polls at 1, 2, 4, 5, 5 s, shows queued then running, and stops once done', async () => {
      const { polls, at } = await start([
        { state: 'queued' },
        { state: 'queued' },
        { state: 'running' },
        { state: 'running' },
        { state: 'done', brief: BRIEF },
      ])
      expect(screen.getByRole('status')).toHaveTextContent('Generating… (queued)')
      await tick(999)
      expect(polls).toHaveLength(0)
      await tick(1)
      expect(polls).toHaveLength(1)
      await tick(2000)
      expect(polls).toHaveLength(2)
      expect(screen.getByRole('status')).toHaveTextContent('Generating… (queued)')
      await tick(4000)
      expect(polls).toHaveLength(3)
      expect(screen.getByRole('status')).toHaveTextContent('Generating… (running)')
      await tick(5000)
      await tick(5000)
      await tick(50) // the brief renders only once the clock moves on: its delivery waits on a (fake) timer
      expect(screen.getByText(BRIEF.summary)).toBeInTheDocument()
      expect(polls.map((p) => p.at - at)).toEqual([1000, 3000, 7000, 12000, 17000])
      expect(polls.every((p) => p.jobId === JOB_ID)).toBe(true)
      await tick(30_000)
      expect(polls).toHaveLength(5) // done: no more polls
    })

    it.each([
      ['AI_BAD_OUTPUT', 'The AI could not write a usable brief for this lead. Try again.', true],
      ['NOT_FOUND', 'This lead was deleted.', false],
    ])(
      'a failed job (%s) shows its message, stops polling, and offers Retry only where it can help',
      async (code, message, retry) => {
        const { polls } = await start([{ state: 'running' }, { state: 'failed', error: { code, message } }])
        await tick(1000)
        await tick(2000)
        expect(screen.getByRole('alert')).toHaveTextContent(message)
        expect(Boolean(screen.queryByRole('button', { name: 'Retry' }))).toBe(retry)
        await tick(30_000)
        expect(polls).toHaveLength(2)
      },
    )

    it('leaving the page stops the polling', async () => {
      const { polls, unmount } = await start([{ state: 'queued' }])
      await tick(1000)
      expect(polls).toHaveLength(1)
      unmount()
      await tick(60_000)
      expect(polls).toHaveLength(1)
    })
  })
})
