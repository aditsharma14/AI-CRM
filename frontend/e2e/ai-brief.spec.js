// @ts-check
// The AI lead brief end to end, on the fake provider: register, create a lead, add a note, open the lead's page,
// generate the brief, follow its citation to the note, and regenerate. Real UI, real API, real AI service.
import { expect, test } from '@playwright/test'

test('a lead brief cites the lead history and regenerates', async ({ page }) => {
  const stamp = Date.now()
  const leadName = `Meera Kulkarni ${stamp}`
  const noteText = `Budget approved for 40 label printers (${stamp})`

  await test.step('register and create a lead with one note', async () => {
    await page.goto('/register')
    await page.getByLabel('Organization name').fill(`AI Org ${stamp}`)
    await page.getByLabel('Your name').fill('Erin Owner')
    await page.getByLabel('Email').fill(`ai.${stamp}@e2e.test`)
    await page.getByLabel('Password').fill('correct-horse-battery')
    await page.getByRole('button', { name: /create/i }).click()
    await expect(page).toHaveURL('/')

    await page.getByRole('navigation').first().getByRole('link', { name: 'Leads' }).click()
    await page.getByRole('button', { name: 'New lead' }).click()
    const create = page.getByRole('dialog', { name: 'New lead' })
    await create.getByLabel('Name').fill(leadName)
    await create.getByRole('button', { name: 'Create' }).click()
    await expect(create).toBeHidden()

    // A lead's name links to its page; another cell of the row opens the edit dialog, which has the notes.
    await page
      .getByRole('row', { name: new RegExp(leadName) })
      .getByRole('cell')
      .nth(2)
      .click()
    const edit = page.getByRole('dialog', { name: 'Edit lead' })
    await edit.getByLabel('New note').fill(noteText)
    await edit.getByRole('button', { name: 'Add' }).click()
    await expect(edit.getByText(noteText)).toBeVisible()
    await edit.getByRole('button', { name: 'Cancel' }).click()
  })

  await test.step("open the lead's page", async () => {
    await page.getByRole('link', { name: leadName }).click()
    await expect(page.getByRole('heading', { name: leadName })).toBeVisible()
    await expect(page.getByRole('listitem').filter({ hasText: noteText })).toBeVisible()
  })

  await test.step('generate the brief and follow its citation to the note', async () => {
    await page.getByRole('button', { name: 'Generate brief' }).click()
    await expect(page.getByText(new RegExp(`${leadName} is a new lead`))).toBeVisible()
    await expect(page.getByText('Generated by AI, check before sending.', { exact: false })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Follow-up email (draft)' })).toBeVisible()

    await page.getByRole('button', { name: /^Note · / }).click()
    const note = page.getByRole('listitem').filter({ hasText: noteText })
    await expect(note).toBeFocused()
    await expect(note).toHaveClass(/ring-2/)
  })

  await test.step('regenerate', async () => {
    await page.getByRole('button', { name: 'Regenerate' }).click()
    await expect(page.getByText(/Generated by AI, check before sending\. Generated /)).toBeVisible()
  })
})
